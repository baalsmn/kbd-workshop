GLYPHS = {' ': ['.' * 8] * ROWS}
for line in _ART.strip().splitlines():
    c, *rows = line.split()
    assert 12 <= len(rows) <= ROWS and all(len(r) == 8 for r in rows), line
    GLYPHS[c] = rows + ['.' * 8] * (ROWS - len(rows))


def c_table():
    """(characters as a C string, rows as C initialisers), bit 7 = the left column."""
    chars = ''.join(GLYPHS)
    rows = ['    {' + ', '.join('0x%02X' % int(r.replace('#', '1').replace('.', '0'), 2) for r in GLYPHS[c]) + '},  // ' + repr(c)
            for c in chars]
    return chars, '\n'.join(rows)
